// Turns the Eurostat GISCO countries layer into SVG paths for the "Unió Europea" pack.
//
//   source: gisco-services.ec.europa.eu, CNTR_RG_10M_2024_3035 — every country in the
//           world at 1:10M, already in EPSG:3035 (Lambert azimuthal equal-area centred
//           on Europe, the projection the EU itself uses), so no projection maths here
//           beyond a scale and a y-flip.
//
// What it produces:
//   - the 27 member states as tappable places (membership read from GISCO's EU_STAT
//     flag and cross-checked against docs/data/ue-hints.js)
//   - every other country inside the frame as grey, untappable context, because an EU
//     country floating in white space is hard to recognise
//
// Overseas territories (Canàries, Madeira, Açores, Guaiana Francesa, Reunió…) are left
// out: the frame is fitted to the European parts of the member states.
//
// Run: node build/fetch-geo-ue.mjs

import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { load, toRings, bbox, ringArea, toPath, centroid, labelAnchor, pointInRings, processLayer,
  clipRing } from './geo-lib.mjs';
import { HINTS } from '../docs/data/ue-hints.js';

const URL = 'https://gisco-services.ec.europa.eu/distribution/v2/countries/geojson/CNTR_RG_10M_2024_3035.geojson';
const OUT = 'docs/data/ue-geo.js';

const WIDTH = 1000;            // SVG user units across
const TARGET = 12000;          // vertices kept after simplification, EU + context
const MIN_RING_AREA = 1.5;     // units² — below this an island is invisible, so drop it
const SMALL = 400;             // units² — places smaller than this get a tap ring

// European parts of the member states fall inside this box (metres, EPSG:3035); the
// overseas territories do not. Only used to choose which polygons count — the frame is
// then fitted to what is kept.
const EUROPE = [2.5e6, 1.3e6, 7.0e6, 5.6e6];

const geo = await load('ue-countries', URL);

const overlaps = (r, [x0, y0, x1, y1]) => {
  const [a, b, c, d] = bbox([{ rings: [[r]] }]);
  return a < x1 && c > x0 && b < y1 && d > y0;
};
const within = (r, [x0, y0, x1, y1]) => {
  const [a, b, c, d] = bbox([{ rings: [[r]] }]);
  return a >= x0 && c <= x1 && b >= y0 && d <= y1;
};

const members = geo.features.filter((f) => f.properties.EU_STAT === 'T');
const eu = members.map((f) => ({
  code: f.properties.CNTR_ID,
  polys: toRings(f.geometry).filter((poly) => within(poly[0], EUROPE)),
}));

// Fit the frame to the kept European parts, with a little sea around them.
const [ex0, ey0, ex1, ey1] = bbox(eu.map((c) => ({ rings: c.polys })));
const m = 0.025 * (ex1 - ex0);
const FRAME = [ex0 - m, ey0 - m, ex1 + m, ey1 + m];
// Context is clipped to a slightly larger window so the cut edges sit outside the view.
const m2 = 0.04 * (ex1 - ex0);
const WINDOW = [FRAME[0] - m2, FRAME[1] - m2, FRAME[2] + m2, FRAME[3] + m2];

const context = geo.features
  .filter((f) => f.properties.EU_STAT !== 'T')
  .map((f) => ({
    code: f.properties.CNTR_ID,
    polys: toRings(f.geometry)
      .filter((poly) => overlaps(poly[0], WINDOW))
      .map((poly) => (within(poly[0], WINDOW) ? poly
        : poly.map((r) => clipRing(r, WINDOW)).filter(Boolean)))
      .filter((poly) => poly.length),
  }))
  .filter((c) => c.polys.length);

const s = WIDTH / (FRAME[2] - FRAME[0]);
const height = +((FRAME[3] - FRAME[1]) * s).toFixed(2);
const projection = {
  project: ([x, y]) => [+((x - FRAME[0]) * s).toFixed(1), +((FRAME[3] - y) * s).toFixed(1)],
};

// One topology for members and context together, so shared borders (Spain–Portugal,
// Poland–Ukraine…) are simplified once and stay welded.
const all = [...eu.map((c) => ({ ...c, member: true })), ...context];
const layer = processLayer(
  { features: all.map((c) => ({ properties: c, geometry: { type: 'MultiPolygon', coordinates: c.polys } })) },
  (p) => ({ code: p.code, member: !!p.member }),
  TARGET, projection, MIN_RING_AREA);

const countries = layer.out.filter((c) => c.member).map((c) => {
  const area = Math.round(c.rings.reduce((n, r) => n + ringArea(r), 0));
  const ctr = centroid(c.rings);
  const label = labelAnchor(c.rings) || ctr;
  return {
    code: c.code, centroid: ctr, label, area, d: toPath(c.rings),
    // Malta and Luxembourg are a few pixels across at full extent: give them a ring that
    // can be seen and tapped.
    ...(area < SMALL ? { mark: label } : {}),
  };
}).sort((a, b) => a.code.localeCompare(b.code));

const contextD = layer.out.filter((c) => !c.member).map((c) => toPath(c.rings)).join('');

mkdirSync('docs/data', { recursive: true });
writeFileSync(OUT,
  `// GENERATED by build/fetch-geo-ue.mjs — do not edit.\n` +
  `// Source: Eurostat GISCO, CNTR_RG_10M_2024 (EPSG:3035). Names and capitals: ue-hints.js\n` +
  `export const VIEWBOX = "0 0 ${WIDTH} ${height}";\n` +
  `export const COUNTRIES = ${JSON.stringify(countries)};\n` +
  `// Every non-member country inside the frame, as one untappable path.\n` +
  `export const CONTEXT = ${JSON.stringify(contextD)};\n`);

const size = readFileSync(OUT).length;
console.log(`
members     ${countries.length} countries
context     ${layer.out.length - countries.length} countries
geometry    ${layer.arcs} arcs, ${layer.kept} pts kept, ${layer.dropped} tiny rings dropped
viewBox     0 0 ${WIDTH} ${height}
small       ${countries.filter((c) => c.mark).map((c) => `${c.code} (${c.area})`).join(', ')}
written     ${OUT}  (${(size / 1024).toFixed(0)} KB)`);

// Integrity: the membership list, the hand-written content and the geometry must agree.
let bad = 0;
const codes = new Set(countries.map((c) => c.code));
if (countries.length !== 27) { console.warn(`!! expected 27 member states, got ${countries.length}`); bad++; }
for (const c of countries) {
  const h = HINTS[c.code];
  if (!h?.name || !h?.capital || !h?.art) { console.warn(`!! ${c.code}: missing name/capital/art in ue-hints.js`); bad++; }
  if (!c.d) { console.warn(`!! ${c.code}: no geometry left after simplification`); bad++; }
  const rings = layer.out.find((x) => x.code === c.code).rings;
  if (!pointInRings(c.label, rings)) { console.warn(`!! ${c.code}: label anchor falls outside the country`); bad++; }
}
for (const code of Object.keys(HINTS)) {
  if (!codes.has(code)) { console.warn(`!! ${code} is in ue-hints.js but not a member state in GISCO`); bad++; }
}
if (bad) process.exitCode = 1;
console.log(bad ? `\n${bad} problem(s) above` : '\nchecks passed: 27 member states, all named, all with a capital');
