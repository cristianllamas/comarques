// Matches the photos you drop into  photos/<topic>/  to that topic's places, resizes them
// into docs/img/<topic>/, and writes docs/data/<topic>-photos.js listing only the ones
// that exist.
//
// Naming is forgiving on purpose: accents, capitals, apostrophes, leading articles and
// spaces-vs-hyphens are all ignored, and the file may be named after either the capital
// or the place. All of these work for the comarques:
//     Berga.jpg   berga.png   Bergà.JPEG   la-seu-durgell.jpg   La Seu d'Urgell.jpg
//
// A place with no photo is not an error — the app just renders that card as text.
//
// Run: node build/scan-photos.mjs cat

import { readdirSync, mkdirSync, writeFileSync, copyFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { extname, basename, join } from 'node:path';
import { loadTopic } from '../docs/topics.js';

const TOPIC = process.argv[2];
if (!TOPIC) { console.error('usage: node build/scan-photos.mjs <topic>   (e.g. cat)'); process.exit(2); }
const { places } = await loadTopic(TOPIC);

const SRC = `photos/${TOPIC}`;
const OUT = `docs/img/${TOPIC}`;
const LIST = `docs/data/${TOPIC}-photos.js`;
const OK = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const WIDTH = 800;

// Order matters: the leading article must go before apostrophes are stripped, and it
// must tolerate any separator, so a file typed `la-bisbal-demporda` still reaches
// `la Bisbal d'Empordà`.
const slug = (s) => s
  .normalize('NFD').replace(/[̀-ͯ]/g, '')   // drop accents
  .toLowerCase()
  .replace(/^(els|les|el|la|l)['’\s_-]+/, '')         // drop a leading article
  .replace(/['’·]/g, '')                              // drop remaining apostrophes
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '');

// every name a file is allowed to be called, mapped back to the place code
const lookup = new Map();
for (const c of places) {
  const names = [c.name, ...String(c.capital || '').split('/').map((s) => s.trim()).filter(Boolean)];
  for (const n of names) {
    const k = slug(n);
    if (!lookup.has(k)) lookup.set(k, c.code);
  }
}

mkdirSync(SRC, { recursive: true });
mkdirSync(OUT, { recursive: true });

let magick = true;
try { execFileSync('magick', ['-version'], { stdio: 'ignore' }); }
catch { magick = false; console.warn('note: ImageMagick not found — copying photos without resizing'); }

const found = {};
const unmatched = [];

for (const file of readdirSync(SRC)) {
  const ext = extname(file).toLowerCase();
  if (!OK.has(ext)) continue;
  const code = lookup.get(slug(basename(file, extname(file))));
  if (!code) { unmatched.push(file); continue; }

  const outName = `${code}.jpg`;
  const src = join(SRC, file), dst = join(OUT, outName);
  if (magick) {
    execFileSync('magick', [src, '-auto-orient', '-resize', `${WIDTH}>`,
      '-strip', '-quality', '82', dst]);
  } else {
    copyFileSync(src, dst);
  }
  found[code] = outName;
}

writeFileSync(LIST,
  `// GENERATED by build/scan-photos.mjs ${TOPIC} — do not edit.\n` +
  '// Only files that actually exist are listed, so the app never requests a missing one.\n' +
  `export const PHOTOS = ${JSON.stringify(found, null, 2)};\n`);

const n = Object.keys(found).length;
console.log(`\n${n}/${places.length} places have a photo  (${LIST})`);
if (unmatched.length) {
  console.warn(`\n${unmatched.length} file(s) in ${SRC}/ matched no place — check the spelling:`);
  for (const f of unmatched) console.warn('  ' + f);
}
if (n < places.length) {
  const missing = places.filter((c) => !found[c.code]);
  console.log(`\nstill without a photo (${missing.length}):`);
  console.log('  ' + missing.map((c) => c.capital || c.name).join(', '));
}
